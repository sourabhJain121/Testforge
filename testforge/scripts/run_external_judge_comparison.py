"""
testforge/scripts/run_external_judge_comparison.py

Stage 1.6: External Mutation Judge (mutmut) Independent Comparison.
Runs mutmut against canonical benchmark targets using TestForge hardened test suites,
extracts independent mutation scores, and computes correlation with TestForge AST mutation scores.

Outputs:
  - qa_artifacts/EXTERNAL_MUTATION_JUDGE_RESULTS.json
  - docs/EXTERNAL_MUTATION_JUDGE.md
"""

